    CREATE OR REPLACE PROCEDURE economia.lancar(
        p_id_grupo   INT,
        p_id_usuario INT,          -- NULL = conta do desafio (escrow)
        p_id_desafio  INT,
        p_tipo       VARCHAR(20),
